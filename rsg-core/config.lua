--[[
    rsg-core (compat bridge) — การตั้งค่าการแปลง
    ---------------------------------------------------------------------
    แก้ไฟล์นี้เมื่อสคริปต์ RSG ที่เอามาลงใช้ชื่อประเภทเงิน / ระดับสิทธิ์
    ที่ hexa_core ไม่มี
]]

BridgeConfig = {}

-- ==========================================
-- ประเภทเงิน
-- ==========================================
-- hexa_core มีสามช่อง: cash / bank / gold (ดู hexa_core/config.lua > Config.Money.MoneyTypes)
-- สคริปต์ qb/rsg มักใช้ชื่ออื่น ตารางนี้แปลงชื่อก่อนส่งเข้า hexa
--   'ชื่อที่สคริปต์ใช้' = 'ช่องของ hexa'   -> แปลงแล้วทำงานปกติ
--   'ชื่อที่สคริปต์ใช้' = false            -> ไม่รองรับ (คืน false + เตือนใน console ครั้งเดียว)
-- ชื่อที่ไม่อยู่ในตารางนี้จะถูกส่งต่อไปตรง ๆ
BridgeConfig.MoneyAliases = {
    money  = 'cash',  -- บางสคริปต์เรียกเงินสดว่า money
    crypto = false,   -- qb มี crypto, hexa ไม่มี — ตั้งเป็น 'bank' ถ้าอยากให้ไหลเข้าธนาคาร
}

-- ==========================================
-- ระดับสิทธิ์
-- ==========================================
-- hexa_core ใช้ ace 'hexacore.<perm>' และมีสองระดับ: admin, staff
-- แปลงชื่อระดับสิทธิ์ของ qb/rsg (god / admin / mod) ให้ตรงกับของ hexa
BridgeConfig.PermissionAliases = {
    god = 'admin',
    mod = 'staff',
}

-- ==========================================
-- ระบบแก๊ง (gang)
-- ==========================================
-- hexa_core ไม่มีระบบแก๊ง แต่สคริปต์ qb/rsg จำนวนมากอ่าน PlayerData.gang.name
-- ตรง ๆ โดยไม่เช็ค nil ก่อน bridge จึงใส่ค่าเริ่มต้นนี้ให้ทุกตัวละคร
-- เพื่อไม่ให้สคริปต์พังตอนอ่าน (ไม่ได้ทำให้ระบบแก๊งใช้งานได้จริง)
BridgeConfig.DefaultGang = {
    name   = 'none',
    label  = 'No Gang',
    isboss = false,
    grade  = { name = 'none', level = 0, isboss = false },
}

-- true = พิมพ์ log ทุกครั้งที่สคริปต์เรียกของที่ bridge ยังไม่รองรับ
BridgeConfig.Debug = false
